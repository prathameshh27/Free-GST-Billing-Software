// Recurring invoices, ported from server.js: "Generate Now" and the hourly
// auto-fire, which now runs for every active business.
import { templateTotals, clientYearToDate, nextCounterValue, startFor, numberSeriesFor, counterKeyFor, formatDocNumber, businessKeyOf, getFinancialYearLabel } from '../../src/utils.js';
import { q, tx } from './db.js';
import * as S from './store.js';

// Calendar arithmetic on YYYY-MM-DD in UTC (no time-zone drift).
const isoDay = (d) => d.toISOString().split('T')[0];
function parseIsoDay(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(s || ''));
  return m ? new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]))) : null;
}
function addDays(s, days) {
  const d = parseIsoDay(s);
  if (!d) return '';
  d.setUTCDate(d.getUTCDate() + days);
  return isoDay(d);
}
// Monthly / quarterly / yearly steps keep the anchor day, clamped to short months.
function advanceDate(s, frequency, interval, anchorDay) {
  const d = parseIsoDay(s);
  if (!d) return s;
  const n = Math.max(1, parseInt(interval, 10) || 1);
  if (frequency === 'weekly') { d.setUTCDate(d.getUTCDate() + 7 * n); return isoDay(d); }
  const months = frequency === 'quarterly' ? 3 * n : frequency === 'yearly' ? 12 * n : n;
  const day = Math.min(31, Math.max(1, parseInt(anchorDay, 10) || d.getUTCDate()));
  const target = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + months, 1));
  const lastDay = new Date(Date.UTC(target.getUTCFullYear(), target.getUTCMonth() + 1, 0)).getUTCDate();
  target.setUTCDate(Math.min(day, lastDay));
  return isoDay(target);
}

// Today in India (the service runs with TZ=Asia/Kolkata; this is a fallback).
export function localToday() {
  const d = new Date(new Date().toLocaleString('en-US', { timeZone: process.env.TZ || 'Asia/Kolkata' }));
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

export const templateIsActive = (tpl) => tpl.active !== false;
export const templateHasEnded = (tpl, today) =>
  (tpl.endMode === 'onDate' && tpl.endDate && today > tpl.endDate)
  || (tpl.endMode === 'afterN' && tpl.maxOccurrences && (tpl.occurrencesCreated || 0) >= tpl.maxOccurrences);

// Reserves the next number atomically (same rules as the app's getNextInvoiceNumber).
async function nextInvoiceNumber(businessId, prefix, invoiceType, businessKey) {
  const settings = await S.getMeta(businessId, 'invoiceNumberSettings');
  const seriesMap = await S.getMeta(businessId, 'invoiceNumberSeries');
  const series = numberSeriesFor(settings, seriesMap, businessKey);
  const key = counterKeyFor(prefix, series, businessKey);
  await S.ensureMeta(businessId, key);
  const next = await tx(async (conn) => {
    const n = nextCounterValue(await S.lockMeta(conn, businessId, key), startFor(invoiceType, series));
    await S.setMeta(businessId, key, n, conn);
    return n;
  });
  return formatDocNumber({ settings: series, typePrefix: prefix, next, fyLabel: getFinancialYearLabel() });
}

const PREFIX = { proforma: 'EST', quotation: 'QUO', 'credit-note': 'CN', 'bill-of-supply': 'BOS', composition: 'COMP', 'delivery-challan': 'DC' };

// Makes ONE invoice from a template and moves the template on.
export async function generateFromTemplate(businessId, tpl, today, userId = null) {
  const profiles = await S.list(businessId, 'profiles');
  const profile = profiles.find((p) => p.gstin && tpl.ownerGstin && p.gstin === tpl.ownerGstin)
    || profiles.find((p) => p.id && tpl.profileId && p.id === tpl.profileId)
    || profiles.find((p) => p.businessName && p.businessName === (tpl.profileBusinessName || tpl.ownerName))
    || await S.getProfile(businessId);

  const prefix = PREFIX[tpl.invoiceType] || 'INV';
  const bizKey = businessKeyOf(profile);
  let invoiceNumber = await nextInvoiceNumber(businessId, prefix, tpl.invoiceType, bizKey);
  for (let i = 0; i < 50 && await S.exists(businessId, 'bills', invoiceNumber); i++) {
    invoiceNumber = await nextInvoiceNumber(businessId, prefix, tpl.invoiceType, bizKey);
  }
  const invoiceDate = today;
  const ytd = clientYearToDate(await S.list(businessId, 'bills'), tpl.clientName, today);
  const totals = templateTotals(tpl, profile, { tcsCumulativeThisYear: ytd, tdsCumulativeThisYear: ytd });
  const dueDays = Number(tpl.dueDays);
  const dueDate = Number.isFinite(dueDays) && dueDays >= 0 && tpl.dueDays !== '' && tpl.dueDays !== null ? addDays(invoiceDate, dueDays) : '';

  const bill = {
    id: invoiceNumber,
    clientName: tpl.clientName,
    invoiceNumber,
    invoiceDate,
    invoiceType: tpl.invoiceType || 'tax-invoice',
    currency: (tpl.invoiceOptions && tpl.invoiceOptions.currency) || 'INR',
    totalAmount: totals.total,
    totalTaxAmount: totals.totalTaxAmount,
    status: 'unpaid',
    paidAmount: 0,
    payments: [],
    generatedFrom: tpl.id,
    autoGenerated: true,
    autoGeneratedAt: new Date().toISOString(),
    data: {
      profile,
      client: {
        name: tpl.clientName, state: tpl.clientState, gstin: tpl.clientGstin,
        address: tpl.clientAddress, country: tpl.clientCountry, city: tpl.clientCity,
        pin: tpl.clientPin, email: tpl.clientEmail, phone: tpl.clientPhone, isSEZ: tpl.isSEZ,
      },
      details: { invoiceNumber, invoiceDate, dueDate, placeOfSupply: tpl.placeOfSupply || '' },
      items: (tpl.items || []).map((i) => ({ ...i, name: i.name || i.description || '' })),
      totals,
      invoiceType: tpl.invoiceType || 'tax-invoice',
      customTerms: tpl.customTerms || '',
      customNotes: tpl.customNotes || '',
      extraSections: tpl.extraSections || [],
      invoiceOptions: tpl.invoiceOptions || {},
      taxInclusive: !!tpl.taxInclusive,
    },
  };
  await S.put(businessId, 'bills', bill, userId);

  const from = tpl.nextDate || today;
  if (!tpl.anchorDay && tpl.frequency !== 'weekly') tpl.anchorDay = Number(from.slice(8, 10)) || undefined;
  tpl.nextDate = advanceDate(from, tpl.frequency, tpl.interval, tpl.anchorDay);
  tpl.lastGenerated = today;
  tpl.occurrencesCreated = (tpl.occurrencesCreated || 0) + 1;
  await S.put(businessId, 'recurring', tpl, userId);
  return invoiceNumber;
}

// Hourly: every active business's due templates. A template fires only once
// its nextDate has come, so checking often never makes extra invoices.
let running = false;
export async function processDueRecurring() {
  if (running) return;
  running = true;
  try {
    const today = localToday();
    const businesses = await q("SELECT id FROM businesses WHERE status = 'active'");
    for (const { id: businessId } of businesses) {
      let fired = 0;
      for (const tpl of await S.list(businessId, 'recurring')) {
        if (!tpl || !templateIsActive(tpl) || !tpl.nextDate || tpl.nextDate > today || templateHasEnded(tpl, today)) continue;
        try {
          const n = await generateFromTemplate(businessId, tpl, today);
          await S.audit({ businessId }, 'create', 'bills', n, 'recurring auto-fire');
          fired += 1;
        } catch (err) {
          console.error(`  [recurring] ${businessId} ${tpl.id}:`, err.message);
        }
      }
      if (fired > 0) await S.setMeta(businessId, 'lastRecurringAutoFire', { date: today, count: fired, at: new Date().toISOString() });
    }
  } finally {
    running = false;
  }
}
